async function featureTest(source) {
  const frame = document.createElement('iframe');
  frame.style.cssText = 'position:fixed;width:1px;height:1px;opacity:0;pointer-events:none';
  document.body.append(frame);
  const w = frame.contentWindow, d = frame.contentDocument;
  const key = 'bili-yt-player-preferences-v1', saved = localStorage.getItem(key);
  const checks = [];
  const check = (condition, label) => { if (!condition) throw new Error(label); checks.push(label); };
  const settle = () => new Promise(resolve => setTimeout(resolve, 80));
  const until = async predicate => {
    for (let i = 0; i < 100; i++) { if (predicate()) return; await settle(); }
    throw new Error('Timed out waiting for audio graph');
  };
  const contexts = [], processors = [];
  let sources = 0;
  const BaseContext = w.AudioContext, BaseProcessor = w.AudioWorkletNode;
  w.AudioContext = class extends BaseContext { constructor(...args) { super(...args); contexts.push(this); } };
  w.AudioWorkletNode = class extends BaseProcessor { constructor(...args) { super(...args); processors.push(this); } };
  const create = w.AudioContext.prototype.createMediaElementSource;
  w.AudioContext.prototype.createMediaElementSource = function (...args) { sources++; return create.apply(this, args); };
  const controls = '<div class="bpx-player-control-bottom-left"><div class="bpx-player-ctrl-time"></div></div><div class="bpx-player-control-bottom-right"><button class="bpx-player-ctrl-volume"></button><div class="bpx-player-ctrl-setting-menu-left"><button class="bpx-player-ctrl-setting-more">More</button></div><div class="bpx-player-ctrl-setting-menu-right"></div></div>';
  let objectUrl;
  try {
    localStorage.removeItem(key);
    w.fixtureLocation = { origin: location.origin, href: location.href, search: '', pathname: '/video/BVtest000001/' };
    w.__INITIAL_STATE__ = { videoData: { bvid: 'BVtest000001', tid_v2: 2020 } };
    w.eval(source.replace("  'use strict';", "  'use strict'; const location = window.fixtureLocation;"));
    const root = d.createElement('div'); root.className = 'bpx-player-container'; root.innerHTML = '<video loop muted crossorigin="anonymous"></video>' + controls; d.body.append(root);
    const video = root.querySelector('video'); video.muted = true; video.volume = .001;
    await settle();
    const toggle = () => root.querySelector('.bpx-player-ctrl-setting-menu-left .bili-yt-setting input');
    await until(toggle);
    check(!toggle().checked, 'Music defaults off');
    const musicDefault = root.querySelector('.bpx-player-ctrl-setting-menu-right .bili-yt-balance-default input[value="all"]');
    check(musicDefault && !musicDefault.checked, 'Music default setting lives in More playback settings and starts off');
    musicDefault.click(); await settle();
    check(toggle().checked && JSON.parse(localStorage.getItem(key)).balanceMode === 'all', 'Music default enables current music and is persisted');
    root.querySelector('.bili-yt-balance-default input[value="except-music"]').click(); await settle();
    check(!toggle().checked && JSON.parse(localStorage.getItem(key)).balanceMode === 'except-music', 'Music default off is applied and persisted');
    check(!d.querySelector('[aria-label*="關燈"]'), 'Removed light feature is absent');
    toggle().click(); await settle();
    check(toggle().checked, 'Music can be enabled for the current video');
    w.fixtureLocation.pathname = '/video/BVtest000002/';
    w.__INITIAL_STATE__.videoData = { bvid: 'BVtest000002', tid_v2: 2016 };
    video.dispatchEvent(new w.Event('loadeddata')); await settle();
    check(!toggle().checked, 'Next music video defaults off even after manual enable');
    w.fixtureLocation.pathname = '/video/BVtest000003/';
    w.__INITIAL_STATE__.videoData = { bvid: 'BVtest000003', tid_v2: 2100 };
    video.dispatchEvent(new w.Event('loadeddata')); await settle();
    check(toggle().checked, 'Non-music defaults on');
    root.querySelector('.bili-yt-balance-default input[value="off"]').click(); await settle();
    check(!toggle().checked && JSON.parse(localStorage.getItem(key)).balanceMode === 'off', 'Off default disables the current non-music video');
    toggle().click(); await settle();
    check(toggle().checked && JSON.parse(localStorage.getItem(key)).balanceMode === 'off', 'Quick toggle affects only the current video, not the default');
    root.querySelector('.bili-yt-balance-default input[value="except-music"]').click(); await settle();
    const native = new w.AudioContext();
    const nativeSource = native.createMediaElementSource(video);
    const gain = native.createGain(); nativeSource.connect(gain); gain.connect(native.destination);
    // Give the existing native graph a real local audio track. Tests remain muted.
    const samples = 48000, bytes = new ArrayBuffer(44 + samples * 2), view = new DataView(bytes);
    const text = (offset, str) => [...str].forEach((c,i) => view.setUint8(offset+i,c.charCodeAt(0)));
    text(0,'RIFF');view.setUint32(4,36+samples*2,true);text(8,'WAVE');text(12,'fmt ');view.setUint32(16,16,true);view.setUint16(20,1,true);view.setUint16(22,1,true);view.setUint32(24,48000,true);view.setUint32(28,96000,true);view.setUint16(32,2,true);view.setUint16(34,16,true);text(36,'data');view.setUint32(40,samples*2,true);
    for (let i=0;i<samples;i++) view.setInt16(44+i*2,Math.sin(i*2*Math.PI*440/48000)*4000,true);
    objectUrl=URL.createObjectURL(new Blob([bytes],{type:'audio/wav'}));
    video.src=objectUrl;
    await native.resume(); await video.play();
    await until(()=>processors.length===1 && !root.querySelector('.bili-yt-setting').dataset.status);
    check(processors[0].context===native && sources===1, 'Reuses native context without a second media source');
    check(video.volume===.001 && processors[0].parameters.get('volume').value===0, 'Mute and exact manual volume are preserved');
    toggle().click(); await settle();
    check(processors[0].parameters.get('enabled').value===0, 'Off bypasses the processor');
    toggle().click(); await settle();
    check(processors[0].parameters.get('enabled').value===1, 'On reuses the same graph');
    gain.disconnect(native.destination); gain.connect(native.destination);
    check(sources===1, 'Native targeted disconnect and reconnect remain valid');
    const later = new w.AudioContext();
    const laterSource = later.createMediaElementSource(video);
    const laterGain = later.createGain();laterSource.connect(laterGain);laterGain.connect(later.destination);await later.resume();
    await until(()=>processors.length===2 && !root.querySelector('.bili-yt-setting').dataset.status);
    check(sources===1 && laterSource.context===later, 'Later native effects use a stream bridge instead of a duplicate source');
    check(processors[1].parameters.get('enabled').value===1, 'Balance follows the later native context');
    const menu = root.querySelector('.bpx-player-ctrl-setting-menu-left');menu.innerHTML='<button class="bpx-player-ctrl-setting-more">More</button>';
    // A bare menu child removal is recovered by the route/lifecycle poll.
    await until(()=>toggle());
    check(root.querySelectorAll('.bili-yt-setting').length===1 && root.querySelectorAll('.bili-yt-balance-default').length===1, 'Settings survive reconstruction without duplication');
    processors[1].dispatchEvent(new w.Event('processorerror'));
    await settle();
    check(toggle().disabled && !toggle().checked, 'Processor failure is reported as unavailable');
    laterGain.disconnect(later.destination); laterGain.connect(later.destination);
    check(sources===1, 'Processor failure restores direct native output');
    const ownRoot = d.createElement('div'); ownRoot.className = 'bpx-player-container'; ownRoot.innerHTML = '<video loop muted crossorigin="anonymous"></video>' + controls;
    const ownVideo = ownRoot.querySelector('video'); ownVideo.muted = true; ownVideo.src = objectUrl; d.body.append(ownRoot);
    await ownVideo.play();
    await until(() => processors.length === 3 && sources === 2);
    const ownedContext = processors[2].context;
    check(ownedContext.state === 'running', 'Standalone player creates its own running audio graph');
    ownRoot.remove(); await until(() => ownedContext.state === 'suspended');
    check(ownedContext.state === 'suspended', 'Detached media suspends its owned context');
    d.body.append(ownRoot); await ownVideo.play(); await until(() => ownedContext.state === 'running');
    check(sources === 2, 'Reinserted media resumes without recreating its source');
    ownVideo.pause();
    video.pause();
    check(video.volume===.001, 'Play and pause never adjust the user volume');
    return checks;
  } finally {
    frame.contentDocument.querySelector('video')?.pause();
    for (const context of contexts) if (context.state!=='closed') await context.close();
    if (objectUrl) URL.revokeObjectURL(objectUrl);
    frame.remove();
    if (saved===null) localStorage.removeItem(key); else localStorage.setItem(key,saved);
  }
}
